def gerar_arquivo():
    """Gera o arquivo C com a fonte"""
    with open('build/gerado/fonte8x16.c', 'w') as f:
        f.write("/* Gerado por tools/gerar_fonte.py. Não editar. */\n")
        f.write("const unsigned char fonte_sagui[256][16] = {\n")
        for codigo in range(256):
            linhas = FONT.get(codigo, bloco(["........"] * 13))
            # Converter para bytes
            bytes_linha = []
            for linha in linhas:
                valor = 0
                for x in range(8):
                    if linha[x] == '#':
                        valor |= 0x80 >> x
                bytes_linha.append(valor)
            # Adicionar 2 linhas de zeros no topo e 1 na base (célula de 16)
            linha_celula = [0, 0] + bytes_linha + [0]
            f.write("    {" + ", ".join(f"0x{v:02X}" for v in linha_celula) + f"}},  /* 0x{codigo:02X} */\n")
        f.write("};\n")
        desenhados = sum(1 for c in range(256) if FONT.get(c) != bloco(["........"] * 13))
        print(f"Gerados {desenhados} caracteres")

if __name__ == '__main__':
    gerar_arquivo()