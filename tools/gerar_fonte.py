# Caractere: lista de 13 strings de 8 colunas
def celula(linhas):
    return ["........"] * 2 + linhas + ["........"] * 1  # 2 linhas topo + 13 + 1 linha base

def bloco(linhas):
    """13 linhas de 8 colunas"""
    assert len(linhas) == 13, f"esperava 13 linhas, veio {len(linhas)}"
    for l in linhas:
        assert len(l) == 8, f"esperava 8 colunas, veio {len(l)}: {l!r}"
        assert all(c in '#.' for c in l), f"caractere invalido em {l!r}"
    return linhas

