def fazer_retangulo(altura, largura, preenchido=True):
    """Cria um retângulo de altura x largura"""
    linhas = []
    for y in range(altura):
        linha = ""
        for x in range(8):
            if preenchido:
                linha += "#......."
            else:
                if x == 0 or x == 7 or y == 0 or y == altura - 1:
                    linha += "#......."
                else:
                    linha += "........"
        linhas.append(linha)
    return linhas

